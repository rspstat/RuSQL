SELECT id, g, COUNT(*) OVER (ORDER BY g) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (ORDER BY g RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (ORDER BY g ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (ORDER BY g RANGE BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (ORDER BY g RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (ORDER BY g RANGE BETWEEN CURRENT ROW AND CURRENT ROW) FROM t ORDER BY id
SELECT id, g, LAST_VALUE(id) OVER (ORDER BY g) FROM t ORDER BY id
SELECT id, g, FIRST_VALUE(id) OVER (ORDER BY g DESC) FROM t ORDER BY id
SELECT id, g, MAX(id) OVER (ORDER BY g) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (PARTITION BY g ORDER BY d) FROM t ORDER BY id
