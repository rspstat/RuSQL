# Window functions with the short frame form and named windows (R46): ROWS UNBOUNDED PRECEDING, ROWS 2 PRECEDING, OVER w, OVER (w ORDER BY ...), WINDOW w AS (...).
SELECT id, SUM(i) OVER (ORDER BY id ROWS UNBOUNDED PRECEDING) FROM t ORDER BY id
SELECT id, SUM(i) OVER (ORDER BY id ROWS 2 PRECEDING) FROM t ORDER BY id
SELECT id, SUM(i) OVER (ORDER BY id ROWS CURRENT ROW) FROM t ORDER BY id
SELECT id, COUNT(*) OVER (ORDER BY id ROWS 1 PRECEDING) FROM t ORDER BY id
SELECT id, SUM(i) OVER (ORDER BY id RANGE UNBOUNDED PRECEDING) FROM t ORDER BY id
SELECT id, SUM(i) OVER (ORDER BY id RANGE CURRENT ROW) FROM t ORDER BY id
SELECT id, g, SUM(i) OVER (PARTITION BY g ORDER BY id ROWS UNBOUNDED PRECEDING) FROM t ORDER BY id
SELECT id, MAX(i) OVER (ORDER BY id ROWS 3 PRECEDING), MIN(i) OVER (ORDER BY id ROWS 3 PRECEDING) FROM t ORDER BY id
SELECT id, SUM(i) OVER (ORDER BY id ROWS UNBOUNDED FOLLOWING) FROM t ORDER BY id
SELECT id, SUM(i) OVER (ORDER BY id ROWS 2 FOLLOWING) FROM t ORDER BY id
SELECT id, SUM(i) OVER w FROM t WINDOW w AS (ORDER BY id) ORDER BY id
SELECT id, SUM(i) OVER w, AVG(d) OVER w FROM t WINDOW w AS (PARTITION BY g ORDER BY id ROWS UNBOUNDED PRECEDING) ORDER BY id
SELECT id, ROW_NUMBER() OVER w, RANK() OVER w FROM t WINDOW w AS (PARTITION BY g ORDER BY i) ORDER BY id
SELECT id, SUM(i) OVER (w ORDER BY id) FROM t WINDOW w AS (PARTITION BY g) ORDER BY id
SELECT id, SUM(i) OVER (w ROWS UNBOUNDED PRECEDING) FROM t WINDOW w AS (PARTITION BY g ORDER BY id) ORDER BY id
SELECT id, SUM(i) OVER w1, COUNT(*) OVER w2 FROM t WINDOW w1 AS (ORDER BY id), w2 AS (PARTITION BY g) ORDER BY id
SELECT id, SUM(i) OVER W FROM t WINDOW w AS (ORDER BY id) ORDER BY id
SELECT id, SUM(i) OVER w FROM t WHERE g < 3 WINDOW w AS (ORDER BY id) ORDER BY id
SELECT id, SUM(i) OVER w FROM t WINDOW w AS (ORDER BY id) ORDER BY id LIMIT 3
SELECT id, SUM(i) OVER w FROM t WINDOW w AS (ORDER BY nosuchcol) ORDER BY id
SELECT id, SUM(i) OVER nosuchwindow FROM t ORDER BY id
SELECT id, SUM(i) OVER (nosuchwindow ORDER BY id) FROM t ORDER BY id
SELECT id, LAG(i) OVER w, LEAD(i, 2) OVER w FROM t WINDOW w AS (ORDER BY id) ORDER BY id
SELECT id, FIRST_VALUE(i) OVER w, LAST_VALUE(i) OVER w FROM t WINDOW w AS (ORDER BY id ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) ORDER BY id
SELECT id, NTILE(3) OVER w FROM t WINDOW w AS (ORDER BY id) ORDER BY id
SELECT id, (SELECT SUM(u.k) OVER w FROM u WHERE u.id = 1 WINDOW w AS (ORDER BY u.id)) FROM t ORDER BY id LIMIT 2
# rows that tie in the ORDER BY are peers: the default frame and RANGE frames take them along (R47)
