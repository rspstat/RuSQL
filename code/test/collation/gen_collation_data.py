"""gen_collation_data.py <weights.json> <out.inc>

Writes code/backend/core/src/collation_data.inc: the weights of MySQL's default collation utf8mb4_0900_ai_ci (primary weights only: case and accents do
not count, a space does) for every code point that the algorithms in collation.cpp do not give by themselves.

weights.json comes from dump_weights.py (needs a real MySQL 8.4 on 127.0.0.1:3391): code point -> HEX(WEIGHT_STRING(char)).

Three kinds of code points are NOT written out, because a rule gives their weights:
  * the Hangul syllables U+AC00..U+D7A3: the weights of their jamo (L, V, [T]) in order;
  * the ideographs and every unassigned code point: the "implicit" weights (FB40 / FB80 / FBC0 + (cp >> 15), (cp & 0x7FFF) | 0x8000);
  * nothing else -- all the others are runs {start, count, kind, number of weights, pool offset}: kind 1 = the last weight goes up by one for each
    following code point, kind 0 = all code points of the run have the same weights.
"""
import json
import sys

weights = {int(k): v for k, v in json.load(open(sys.argv[1])).items()}


def ws(cp):
    h = weights[cp]
    return tuple(int(h[i:i + 4], 16) for i in range(0, len(h), 4))


def implicit(cp):
    if 0x4E00 <= cp <= 0x9FFF or cp in (0xFA0E, 0xFA0F, 0xFA11, 0xFA13, 0xFA14, 0xFA1F, 0xFA21, 0xFA23, 0xFA24, 0xFA27, 0xFA28, 0xFA29):
        base = 0xFB40
    elif 0x3400 <= cp <= 0x4DBF or 0x20000 <= cp <= 0x2A6DF or 0x2A700 <= cp <= 0x2EBEF:
        base = 0xFB80
    else:
        base = 0xFBC0
    return (base + (cp >> 15), (cp & 0x7FFF) | 0x8000)


explicit = sorted(cp for cp in weights if not (0xAC00 <= cp <= 0xD7A3) and ws(cp) != implicit(cp))


def continues(a, b, kind):
    wa, wb = ws(a), ws(b)
    if b != a + 1 or len(wa) != len(wb):
        return False
    if kind == 1:
        return len(wa) > 0 and wa[:-1] == wb[:-1] and wb[-1] == wa[-1] + 1
    return wa == wb


runs = []
i = 0
while i < len(explicit):
    best = (0, i)
    for kind in (1, 0):
        j = i
        while j + 1 < len(explicit) and continues(explicit[j], explicit[j + 1], kind):
            j += 1
        if j > best[1] or (j == best[1] and kind == 1 and best[0] == 0 and j > i):
            best = (kind, j)
    kind, j = best
    runs.append((explicit[i], j - i + 1, kind, ws(explicit[i])))
    i = j + 1

pool = []
lines = []
for start, count, kind, first in runs:
    assert count < 65536 and len(first) <= 8
    lines.append("{0x%X,%d,%d,%d,%d}" % (start, count, kind, len(first), len(pool)))
    pool.extend(first)

with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
    f.write("// generated by code/test/collation/gen_collation_data.py from the WEIGHT_STRING of a real MySQL 8.4 (utf8mb4_0900_ai_ci): do not edit\n")
    f.write("// {first code point, number of code points, kind (1: the last weight goes up by one per code point, 0: all the same), number of weights, offset in kPool}\n")
    f.write("const Run kRuns[] = {\n")
    for k in range(0, len(lines), 8):
        f.write("    " + ",".join(lines[k:k + 8]) + ",\n")
    f.write("};\n")
    f.write("const std::uint16_t kPool[] = {\n")
    for k in range(0, len(pool), 16):
        f.write("    " + ",".join("0x%X" % x for x in pool[k:k + 16]) + ",\n")
    f.write("};\n")
print("runs:", len(runs), "pool:", len(pool), "explicit code points:", len(explicit))
